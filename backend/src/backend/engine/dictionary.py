def sanitize_khmer_coeng(text: str) -> str:
    """
    Ensures no standalone or dangling Coeng (\\u17D2 / ្) exists without
    a preceding and succeeding Khmer consonant.
    Prevents the dotted-circle artifact (◌្ and ◌ំ).
    """
    # 1. Join spaces between consonants and Coeng
    text = re.sub(r'([\u1780-\u17A2\u17B1])\s+\u17D2', '\\1្', text)
    text = re.sub(r'\u17D2\s+([\u1780-\u17A2])', '្\\1', text)
    # Strip space before any dependent vowel or accent
    text = re.sub(r'\s+([\u17B6-\u17CD])', r'\1', text)
    # 2. Strip any Coeng not preceded by a Khmer consonant or independent vowel OO (\u17B1 for ឱ្យ)
    text = re.sub(r'(?<![\u1780-\u17A2\u17B1])\u17D2', '', text)
    # 3. Strip any Coeng not followed by a Khmer consonant
    text = re.sub(r'\u17D2(?![\u1780-\u17A2])', '', text)
    # 4. Deduplicate repeated ផ before ផ្ទុក
    text = re.sub(r'ផ+ផ្ទុក', 'ផ្ទុក', text)
    # 5. Deduplicate repeated ស្រាយ after ដោះស្រាយ
    text = re.sub(r'(ដោះស្រាយ)(?:\s*ស្រាយ)+', r'\1', text)
    # 6. Fix repeated យូ in កុំព្យូទ័រ
    text = re.sub(r'កុំព្យូយូ', 'កុំព្យូ', text)
    # 7. Deduplicate redundant Srak Aa and strip space before Srak Aa (prevents dotted circle ◌ា)
    text = re.sub(r'ជា\s*ា+', 'ជា', text)
    text = re.sub(r'(\u17B6){2,}', r'\1', text)
    # 8. Clean up broken គ្ន ន to គ្នា
    text = re.sub(r'គ្ន\s*ន', 'គ្នា', text)
    return text


def clean_khmer_unicode(text: str) -> str:
    """Normalize and clean Khmer Unicode string using NFC and standard rules."""
    if not text:
        return ""
    # Strip zero-width space characters that break word matching
    text = text.replace('\u200b', '')
    # Unicode NFC normalization
    text = unicodedata.normalize('NFC', text)
    return text


def repair_khmer_heuristics(text: str) -> Tuple[str, List[Dict[str, str]]]:
    """
    Applies heuristic repair rules to Khmer text.
    Returns (repaired_text, list_of_applied_rules).
    """
    if not text:
        return "", []
    
    current = clean_khmer_unicode(text)
    applied = []
    
    for pattern, repl, desc in HEURISTIC_RULES:
        if pattern.search(current):
            new_text = pattern.sub(repl, current)
            if new_text != current:
                applied.append({
                    "rule": desc,
                    "before": current,
                    "after": new_text
                })
                current = new_text

    current = sanitize_khmer_coeng(current)
    return current, applied


def replace_dictionary_terms(text: str, custom_dict: Dict[str, str] = None) -> Tuple[str, List[Tuple[str, str]]]:
    """
    Replaces known corrupted terms with clean Unicode terms.
    Checks exact matches and substring replacements (longest matches first).
    Returns (corrected_text, list_of_replacements).
    """
    if not text:
        return "", []
        
    combined_dict = dict(KHMER_CORRUPTION_DICTIONARY)
    if custom_dict:
        combined_dict.update(custom_dict)
        
    # Sort keys by length descending to match longest phrases first
    sorted_keys = sorted(combined_dict.keys(), key=len, reverse=True)
    
    current = text
    replacements = []
    
    for key in sorted_keys:
        val = combined_dict[key]
        if key in current and key != val:
            current = current.replace(key, val)
            replacements.append((key, val))
            
    current = sanitize_khmer_coeng(current)
    return current, replacements


def extract_word_level_differences(orig: str, fixed: str) -> List[Tuple[str, str]]:
    """
    Compares original text with corrected text using Khmer word segmentation
    and extracts distinct word/token replacements.
    """
    if orig == fixed or not orig.strip() or not fixed.strip():
        return []
    import difflib
    try:
        from .khmer_validator import khmer_validator
        t_orig = khmer_validator.segment_text(orig)
        t_fixed = khmer_validator.segment_text(fixed)
    except Exception:
        t_orig = re.findall(r'[\u1780-\u17FF]+|[^\u1780-\u17FF\s]+|\s+', orig)
        t_fixed = re.findall(r'[\u1780-\u17FF]+|[^\u1780-\u17FF\s]+|\s+', fixed)

    s = difflib.SequenceMatcher(None, t_orig, t_fixed)
    replacements = []
    for tag, i1, i2, j1, j2 in s.get_opcodes():
        if tag in ('replace', 'delete', 'insert'):
            o_sub = ''.join(t_orig[i1:i2]).strip()
            f_sub = ''.join(t_fixed[j1:j2]).strip()
            if o_sub and f_sub and o_sub != f_sub:
                replacements.append((o_sub, f_sub))
    return replacements


def restore_khmer_text(text: str, custom_dict: Dict[str, str] = None) -> Tuple[str, List[Tuple[str, str]]]:
    """
    Unified high-level restoration function:
    NFC normalization -> Dictionary replacement -> Algorithmic decoding & Auto-repair -> Heuristic rules -> Coeng sanitization.
    Returns (corrected_text, list_of_word_replacements).
    """
    if not text:
        return "", []
    text = clean_khmer_unicode(text)
    
    # 1. Exact corruption terms replacement first
    fixed, matches = replace_dictionary_terms(text, custom_dict)

    # 2. Algorithmic legacy glyph decoder & dynamic character repair verified by 56,840-word dictionary
    try:
        from .khmer_validator import khmer_validator
        fixed = khmer_validator.decode_and_validate(fixed)
    except Exception:
        pass
        
    fixed, _ = repair_khmer_heuristics(fixed)
    fixed = sanitize_khmer_coeng(fixed)

    # Extract word-level differences between original text and final fixed text
    diffs = extract_word_level_differences(text, fixed)
    
    # Combine matches with word-level diffs without duplicates
    combined = list(matches)
    seen_origs = {m[0] for m in combined}
    for o_w, r_w in diffs:
        if o_w not in seen_origs and o_w != r_w:
            combined.append((o_w, r_w))
            seen_origs.add(o_w)

    return fixed, combined

